/**
 * Returns an Unsplash URL that uses a random image based on the provided title keywords.
 */
function getUnsplashThumbnailUrl(
  title: string,
  width = 400,
  height = 300,
): string {
  return `https://source.unsplash.com/random/${width}x${height}/?${encodeURIComponent(title)}`;
}

